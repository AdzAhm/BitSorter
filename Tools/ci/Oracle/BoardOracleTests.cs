using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using BitSorter.Board;
using BitSorter.Board.Tests;
using BitSorter.Sim;
using NUnit.Framework;

namespace BitSorter.Ci.Oracle
{
    /// <summary>
    /// Part 7a: a drawn board, printed, runs under Icarus as it runs in BitSorter -- the cells, the
    /// testbench made from its stimulus, its hierarchy and registers -- every signal of the design and
    /// the testbench agreeing. What BitSorter exports is what Icarus (and so ModelSim) would run.
    /// </summary>
    public class BoardOracleTests
    {
        [TestCaseSource(typeof(SampleBoards), nameof(SampleBoards.Names))]
        public void APrintedBoard_RunsUnderIcarus_AsItRunsHere(string board)
        {
            Icarus icarus = Icarus.Require();
            Project project = SampleBoards.Build(board);
            CompiledProject compiled = BoardCompiler.Compile(project);
            Assert.IsTrue(compiled.Succeeded, string.Join("\n", compiled.Diagnostics));

            Elaboration elaboration = Elaborator.Elaborate(compiled.Tree, compiled.Top);
            Assert.IsFalse(elaboration.HasErrors, string.Join("\n", elaboration.Diagnostics));
            Design design = elaboration.Design;
            var sim = new Simulator(design);
            RunResult result = sim.RunTo(1_000_000);
            Assert.AreEqual(RunStatus.Finished, result.Status, string.Join("\n", sim.History.Messages));

            Dictionary<string, VcdTrace> theirs = RunIcarus(icarus, BoardPrinter.Print(compiled), compiled.Top);

            // The testbench ends on $stop, and Icarus's dump loses the step a $stop ends in
            // (Docs/oracle-notes.md); that step is BitSorter's alone.
            long until = result.Time - 1;
            var wrong = new List<string>();
            int compared = 0, changes = 0;

            for (int s = 0; s < design.Signals.Count; s++)
            {
                SignalInfo info = design.Signals[s];
                if (info.Local || info.Memory != null)
                    continue;

                if (!theirs.TryGetValue(info.Name, out VcdTrace trace))
                {
                    wrong.Add($"{info.Name}: not in Icarus's dump");
                    continue;
                }

                string[] icarusChanges = trace.Changes.Select(c => $"{c.Time} {c.Bits}").ToArray();
                string[] ours = sim.History.SettledChanges(design.SignalAt(s))
                    .Where(c => c.Time <= until)
                    .Select(c => $"{c.Time} {c.Value.Format(SystemVerilog.Radix.Binary)}")
                    .ToArray();
                compared++;
                changes += ours.Length;

                if (!icarusChanges.SequenceEqual(ours))
                    wrong.Add($"{info.Name}\n      BitSorter {string.Join(", ", ours)}\n      Icarus    {string.Join(", ", icarusChanges)}");
            }

            TestContext.WriteLine($"{board}: {compared} signals, {changes} settled changes compared");
            Assert.IsEmpty(wrong, $"{wrong.Count} signals disagree with Icarus:\n  " + string.Join("\n  ", wrong.Take(16)));
            Assert.Greater(compared, 0);
        }

        private static Dictionary<string, VcdTrace> RunIcarus(Icarus icarus, IReadOnlyList<PrintedSource> printed, string top)
        {
            string folder = Path.Combine(Path.GetTempPath(), "bitsorter-board-oracle", Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(folder);

            try
            {
                var sources = new List<string>();
                foreach (PrintedSource source in printed)
                {
                    string path = Path.Combine(folder, source.Path);
                    File.WriteAllText(path, source.Text);
                    sources.Add(path);
                }

                string dump = Path.Combine(folder, "oracle_dump.sv");
                File.WriteAllText(dump,
                    "// Generated by BoardOracleTests; deleted after the run.\n" +
                    "module oracle_dump;\n" +
                    $"    initial begin $dumpfile(\"oracle.vcd\"); $dumpvars(0, {top}); end\n" +
                    "endmodule\n");
                sources.Add(dump);

                using IcarusRun run = icarus.Simulate(sources, null, null, TimeSpan.FromMinutes(2));
                Assert.IsTrue(run.Succeeded, run.Explain());

                using var vcd = new StreamReader(Path.Combine(run.Folder, "oracle.vcd"));
                return VcdReader.Read(vcd);
            }
            finally
            {
                Directory.Delete(folder, recursive: true);
            }
        }
    }
}
