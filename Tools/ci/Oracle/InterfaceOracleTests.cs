using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using BitSorter.Sim;
using BitSorter.SystemVerilog.Syntax;
using NUnit.Framework;

namespace BitSorter.Ci.Oracle
{
    /// <summary>
    /// Interface ports and modports (Part L8), which Icarus 12 does not read at all, held to Icarus by what they
    /// mean: a module given an interface through a port reaches the instance it was given, so the same design
    /// written with every <c>bus.x</c> spelled out as <c>top.hs.x</c> must run the same. BitSorter runs both forms
    /// and Icarus the spelled-out one, and all three print the same lines; BitSorter's two record the same history
    /// on every signal they share.
    /// </summary>
    /// <remarks>
    /// The designs are written here rather than in the corpus, where Icarus must read every file as it is. They
    /// are race-free on purpose: the source drives on the falling edge and the sink and the watcher sample on the
    /// rising one, answering with nonblocking writes, so the order the simulators start processes in cannot show.
    /// </remarks>
    public class InterfaceOracleTests
    {
        /// <summary>The design with interface ports: a modport on each side, one chosen at the connection, a generic port passed on.</summary>
        private const string WithPorts = @"// Generated by InterfaceOracleTests: interface ports and modports.
interface handshake #(parameter W = 8) (input logic clk);
    logic [W-1:0] data;
    logic valid, ready;
    int sent;

    function automatic logic fire();
        return valid && ready;
    endfunction

    task automatic send(input logic [W-1:0] value);
        @(negedge clk);
        data = value;
        valid = 1;
        @(posedge clk);
        while (!ready) @(posedge clk);
        sent++;
    endtask

    task automatic idle();
        @(negedge clk);
        valid = 0;
    endtask

    modport source (output data, valid, input ready, clk, import send, idle);
    modport sink (input data, valid, clk, output ready, import fire);
    modport monitor (input data, valid, ready, clk);
endinterface

module producer (handshake.source bus);
    initial begin
        bus.valid = 0;
        bus.send(8'h5a);
        bus.send(8'h0f);
        bus.send(8'hc3);
        bus.idle();
    end
endmodule

module consumer (handshake.sink bus, output logic [7:0] last, output int count);
    logic [1:0] phase;
    initial begin
        bus.ready = 0;
        phase = 0;
        count = 0;
    end

    always @(posedge bus.clk) begin
        if (bus.fire()) begin
            last <= bus.data;
            count <= count + 1;
        end
        phase <= phase == 2 ? 0 : phase + 1;
        bus.ready <= phase != 0;
    end
endmodule

module relay (interface bus, output logic [7:0] last, output int count);
    consumer c (.bus(bus), .last(last), .count(count));
endmodule

module watcher (handshake bus);
    always @(posedge bus.clk)
        if (bus.valid) $display(""%0t offered %h, ready %b"", $time, bus.data, bus.ready);
endmodule

module top;
    logic clk = 0;
    always #1 clk = ~clk;
    logic [7:0] last;
    int count;

    handshake #(.W(8)) hs (.clk(clk));
    producer p (.bus(hs.source));
    relay r (hs, last, count);
    watcher w (.bus(hs.monitor));

    initial begin
        #30;
        $display(""%0t last=%h count=%0d sent=%0d fire=%b"", $time, last, count, hs.sent, hs.fire());
        $finish;
    end
endmodule
";

        /// <summary>The same design with every interface port spelled out as the instance it is given, which Icarus 12 reads.</summary>
        private const string SpelledOut = @"// Generated by InterfaceOracleTests: the same design, the interface reached by its full name.
interface handshake #(parameter W = 8) (input logic clk);
    logic [W-1:0] data;
    logic valid, ready;
    int sent;

    function automatic logic fire();
        return valid && ready;
    endfunction

    task automatic send(input logic [W-1:0] value);
        @(negedge clk);
        data = value;
        valid = 1;
        @(posedge clk);
        while (!ready) @(posedge clk);
        sent++;
    endtask

    task automatic idle();
        @(negedge clk);
        valid = 0;
    endtask
endinterface

module producer;
    initial begin
        top.hs.valid = 0;
        top.hs.send(8'h5a);
        top.hs.send(8'h0f);
        top.hs.send(8'hc3);
        top.hs.idle();
    end
endmodule

module consumer (output logic [7:0] last, output int count);
    logic [1:0] phase;
    initial begin
        top.hs.ready = 0;
        phase = 0;
        count = 0;
    end

    always @(posedge top.hs.clk) begin
        if (top.hs.fire()) begin
            last <= top.hs.data;
            count <= count + 1;
        end
        phase <= phase == 2 ? 0 : phase + 1;
        top.hs.ready <= phase != 0;
    end
endmodule

module relay (output logic [7:0] last, output int count);
    consumer c (.last(last), .count(count));
endmodule

module watcher;
    always @(posedge top.hs.clk)
        if (top.hs.valid) $display(""%0t offered %h, ready %b"", $time, top.hs.data, top.hs.ready);
endmodule

module top;
    logic clk = 0;
    always #1 clk = ~clk;
    logic [7:0] last;
    int count;

    handshake #(.W(8)) hs (.clk(clk));
    producer p ();
    relay r (last, count);
    watcher w ();

    initial begin
        #30;
        $display(""%0t last=%h count=%0d sent=%0d fire=%b"", $time, last, count, hs.sent, hs.fire());
        $finish;
    end
endmodule
";

        [Test]
        public void ADesignWithInterfacePorts_RunsAsTheSameDesignSpelledOut_AndAsIcarusRunsThat()
        {
            Icarus icarus = Icarus.Require();

            Simulator ports = Run(WithPorts, "with_ports.sv");
            Simulator spelled = Run(SpelledOut, "spelled_out.sv");
            string[] withPorts = Printed(ports), spelledOut = Printed(spelled);

            string folder = Path.Combine(Path.GetTempPath(), "bitsorter-oracle-generated", Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(folder);
            try
            {
                string file = Path.Combine(folder, "spelled_out.sv");
                File.WriteAllText(file, SpelledOut);
                using IcarusRun run = icarus.Simulate(new[] { file }, "top");
                Assert.IsTrue(run.Succeeded, run.Explain());

                string[] theirs = run.Simulate.StandardOutput.Replace("\r", "").Split('\n')
                    .Where(l => l.Length > 0 && !l.Contains(": $finish called at ")).ToArray();

                Assert.AreEqual(6, withPorts.Length, "six lines printed: " + string.Join(" | ", withPorts));
                Assert.AreEqual("30 last=c3 count=3 sent=3 fire=0", withPorts[5], "sanity: three values offered, all three taken");
                Assert.IsTrue(withPorts.Any(l => l.EndsWith("ready 0")), "sanity: the sink held the source back at least once");
                CollectionAssert.AreEqual(spelledOut, withPorts, "with ports, and spelled out, in BitSorter");
                CollectionAssert.AreEqual(theirs, spelledOut, "spelled out, in BitSorter and in Icarus");
            }
            finally
            {
                Directory.Delete(folder, recursive: true);
            }

            // Every signal the two share, by its full name -- the interface instance's among them -- moves the same.
            var wrong = new List<string>();
            int compared = 0;
            for (int s = 0; s < spelled.Design.Signals.Count; s++)
            {
                SignalInfo info = spelled.Design.Signals[s];
                if (info.Local || info.Memory != null)
                    continue;

                int other = Enumerable.Range(0, ports.Design.Signals.Count).FirstOrDefault(i => ports.Design.Signals[i].Name == info.Name && !ports.Design.Signals[i].Local, -1);
                if (other < 0)
                {
                    wrong.Add($"{info.Name}: not in the design with ports");
                    continue;
                }

                string[] a = Changes(spelled, s), b = Changes(ports, other);
                compared++;
                if (!a.SequenceEqual(b))
                    wrong.Add($"{info.Name}\n      spelled out {string.Join(", ", a)}\n      with ports  {string.Join(", ", b)}");
            }

            Assert.IsEmpty(wrong, string.Join("\n  ", wrong));
            Assert.Greater(compared, 8, "sanity: the interface's signals and the testbench's were compared");
        }

        private static Simulator Run(string text, string name)
        {
            SyntaxTree tree = SyntaxReader.ReadText(text, name);
            Assert.IsEmpty(tree.Diagnostics, string.Join("\n", tree.Diagnostics));
            Elaboration elaboration = Elaborator.Elaborate(tree, "top");
            Assert.IsFalse(elaboration.HasErrors, string.Join("\n", elaboration.Diagnostics));
            Assert.IsEmpty(elaboration.Diagnostics, string.Join("\n", elaboration.Diagnostics));

            var sim = new Simulator(elaboration.Design, null, null);
            Assert.AreEqual(RunStatus.Finished, sim.RunTo(100).Status);
            return sim;
        }

        private static string[] Printed(Simulator sim) =>
            sim.History.Messages.Where(m => m.Severity == Severity.Info && !m.Text.StartsWith("$finish", StringComparison.Ordinal)).Select(m => m.Text).ToArray();

        private static string[] Changes(Simulator sim, int signal) =>
            sim.History.SettledChanges(sim.Design.SignalAt(signal)).Select(c => $"{c.Time} {c.Value.Format(SystemVerilog.Radix.Binary)}").ToArray();
    }
