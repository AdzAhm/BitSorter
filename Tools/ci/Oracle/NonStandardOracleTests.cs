using System;
using System.IO;
using System.Linq;
using BitSorter.Sim;
using BitSorter.SystemVerilog.Syntax;
using NUnit.Framework;

namespace BitSorter.Ci.Oracle
{
    /// <summary>
    /// What the course writes that the standard does not have, run in both simulators. The design is
    /// written here rather than in the corpus, because every corpus file must read with no diagnostics
    /// and these draw a warning on purpose.
    /// </summary>
    public class NonStandardOracleTests
    {
        /// <summary>
        /// The course's first workshop writes a NAND three ways, one of them <c>assign Z = X ~&amp; Y;</c>.
        /// The standard has <c>~&amp;</c> and <c>~|</c> only as reductions; Icarus reads them between two
        /// operands as NAND and NOR, and so does BitSorter, with a warning.
        /// </summary>
        private const string BinaryNandNor = @"// Generated by NonStandardOracleTests: X ~& Y and X ~| Y between two operands.
module binary_nand_nor;
    logic X, Y, Z1, Z2, Z3, W;
    logic [3:0] A, B, V;
    nand g1 (Z1, X, Y);
    assign Z2 = X ~& Y;
    always_comb
        if (X) Z3 = ~Y;
        else   Z3 = 1;
    assign W = X ~| Y;
    assign V = A ~& B ~| 4'b0011;
    initial begin
        A = 4'b01xz; B = 4'b1100;
        X = 0; Y = 0;   #1 $display(""%b %b %b %b %b"", Z1, Z2, Z3, W, V);
        X = 0; Y = 1;   #1 $display(""%b %b %b %b %b"", Z1, Z2, Z3, W, V);
        X = 1; Y = 0;   #1 $display(""%b %b %b %b %b"", Z1, Z2, Z3, W, V);
        X = 1; Y = 1;   #1 $display(""%b %b %b %b %b"", Z1, Z2, Z3, W, V);
        X = 1'bx; Y = 0; #1 $display(""%b %b %b %b %b"", Z1, Z2, Z3, W, V);
        X = 1'bz; Y = 1; #1 $display(""%b %b %b %b %b"", Z1, Z2, Z3, W, V);
    end
endmodule
";

        [Test]
        public void BinaryNandAndNor_AgreeWithIcarus_AndAreWarnedAbout()
        {
            Icarus icarus = Icarus.Require();

            SyntaxTree tree = SyntaxReader.ReadText(BinaryNandNor, "binary_nand_nor.sv");
            CollectionAssert.AreEqual(new[] { DiagnosticCodes.NonStandardOperator, DiagnosticCodes.NonStandardOperator, DiagnosticCodes.NonStandardOperator, DiagnosticCodes.NonStandardOperator },
                tree.Diagnostics.Select(d => d.Code), string.Join("\n", tree.Diagnostics));
            Assert.IsTrue(tree.Diagnostics.All(d => d.Severity == DiagnosticSeverity.Warning));

            Elaboration elaboration = Elaborator.Elaborate(tree, "binary_nand_nor");
            Assert.IsFalse(elaboration.HasErrors, string.Join("\n", elaboration.Diagnostics));
            var sim = new Simulator(elaboration.Design, null, null);
            sim.RunTo(100);
            string[] ours = sim.History.Messages.Where(m => m.Severity == Severity.Info).Select(m => m.Text).ToArray();

            string folder = Path.Combine(Path.GetTempPath(), "bitsorter-oracle-generated", Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(folder);
            try
            {
                string file = Path.Combine(folder, "binary_nand_nor.sv");
                File.WriteAllText(file, BinaryNandNor);
                using IcarusRun run = icarus.Simulate(new[] { file }, "binary_nand_nor");
                Assert.IsTrue(run.Succeeded, run.Explain());

                string[] theirs = run.Simulate.StandardOutput.Replace("\r", "").Split('\n').Where(l => l.Length > 0).ToArray();
                Assert.AreEqual(6, ours.Length, "six lines printed here");
                CollectionAssert.AreEqual(theirs, ours);
                // (01xz ~& 1100) ~| 0011: ~(0100) = 1011, then ~(1011 | 0011) = 0100.
                Assert.AreEqual("1 1 1 1 0100", ours[0], "sanity: 0 ~& 0 is 1, and ~| binds below ~& as | binds below &");
            }
            finally
            {
                Directory.Delete(folder, recursive: true);
            }
        }
    }
}
