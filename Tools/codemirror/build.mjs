// Bundles src/bitsorter-code.js and the CodeMirror packages it imports into one file, Assets/Plugins/WebGL/codemirror.jspre,
// which Unity puts at the head of a browser build's code: the editor ships with the game and is never fetched at run time.
// Its header names every package bundled, its version and its licence, as the MIT licence asks.

import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "..", "Assets", "Plugins", "WebGL", "codemirror.jspre");
const lock = JSON.parse(readFileSync(join(here, "package-lock.json"), "utf8"));

const result = await build({
  entryPoints: [join(here, "src", "bitsorter-code.js")],
  bundle: true,
  minify: true,
  format: "iife",
  target: ["es2019"],
  legalComments: "none",
  metafile: true,
  write: false,
});

// Every package that went into the bundle, from the metafile, with its version and licence from the lock file.
const bundled = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (match)
    bundled.add(match[1]);
}

let header = "// CodeMirror 6 for BitSorter's browser build (Part 12f). Generated by Tools/codemirror/build.mjs -- do not edit;\n";
header += "// rebuild with Tools/codemirror/build.ps1. Bundled, each under the MIT licence unless it says otherwise:\n";
for (const name of [...bundled].sort()) {
  const entry = lock.packages["node_modules/" + name] || {};
  let licence = entry.license || "MIT";
  let notice = "";
  try {
    const text = readFileSync(join(here, "node_modules", name, "LICENSE"), "utf8");
    const line = text.split("\n").find((l) => /copyright/i.test(l));
    notice = line ? " -- " + line.trim() : "";
  } catch {
    notice = "";
  }
  header += `//   ${name} ${entry.version} (${licence})${notice}\n`;
}
header += "// The MIT licence, as each of the packages above is given under it, in full:\n";
header += "//\n";
header += "// Permission is hereby granted, free of charge, to any person obtaining a copy of this software and associated\n";
header += "// documentation files (the \"Software\"), to deal in the Software without restriction, including without limitation the\n";
header += "// rights to use, copy, modify, merge, publish, distribute, sublicense, and/or sell copies of the Software, and to permit\n";
header += "// persons to whom the Software is furnished to do so, subject to the following conditions:\n";
header += "//\n";
header += "// The above copyright notice and this permission notice shall be included in all copies or substantial portions of the\n";
header += "// Software.\n";
header += "//\n";
header += "// THE SOFTWARE IS PROVIDED \"AS IS\", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT NOT LIMITED TO THE\n";
header += "// WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE AUTHORS OR\n";
header += "// COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR\n";
header += "// OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE.\n";

const code = new TextDecoder().decode(result.outputFiles[0].contents);
writeFileSync(out, header + code);
console.log(`wrote ${out}: ${(header.length + code.length).toLocaleString()} bytes, ${bundled.size} packages`);
